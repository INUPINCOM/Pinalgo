def solution(numbers):
    answer = ''
    sorted_list = []
    #기본 원칙: 10의 자리 이상은 소수점으로 계산. ex)143=>1.43
    #부가 원칙: 1과 1.0이 있다면 소수점이 없는 것이 무조건 더 큰 것.->하지만 1.01과 1은? 1.1은 1과 같다. 1.12는 1보다 크다. 1.11은 1과 같다. 1.110은 1보다 작다. 1.01은 1보다 작다.->만약 뒤에 '맨 앞 수'보다 작은 수가 온다면 그건 '맨 앞 수'보다 작다.->3.2는 3보다 크다고 판별할 것이므로, '맨 앞 수'가 같은 수들은 따로 계산할 필요가 있다.->어떻게? 소수점이 있는 수들은 그들끼리 정렬해도 대소가 알맞다. 문제는 소수점이 없는 정수이다. 1은 사실상 1.11111..로 계산되어야 한다.
    #반례: 343, 34->34334가 34343보다 작다. 소수끼리 정렬해도 대소가 알맞지 않다. 그 기준은? 344만 해도 34434가 맞을 것이다. 342, 34는 34342가 맞다. ..기준은 '맨 앞 수'이다. 0이 아니라. 0은 곧 '맨 앞 수'로 여겨야 한다.
    #반례2: 32, 3233->네 규칙이 맞다면 둘은 같아야 한다. 하지만 323233보다 323332가 더 크다. 왜? 32와 '정확히 동치'인 수는 '3232' 이다. 왼쪽과 오른쪽에 똑같은 수가 왔을 때 같기 때문이다.->padding
    #반례3: 아니; 중복된 수 나올 수 있었냐고. 안 된다는 말은 없긴 하네
    
    for i in range(len(numbers)):
        num_str = str(numbers[i])
        padding_val = (num_str * 4)[:4]  # 4자리까지만 자르기
        compare_key = int(padding_val)
        
        # (비교 키, 원래 숫자, 원본 인덱스)를 튜플로 묶어서 리스트에 추가
        sorted_list.append((compare_key, numbers[i], i))
    
    def x(item): return item[0]
    # 비교 키(첫 번째 요소)를 기준으로 내림차순 정렬
    sorted_list.sort(key = x, reverse = True)
    
    # 정렬된 결과에서 원본 숫자를 문자열로 이어 붙이기
    for item in sorted_list:
        answer += str(item[1])
    
    # 중복된 수 반례->그러니까, 맨 앞 자리가 0인 경우.
    if answer[0] == '0':
        answer = str(int(answer))
        
    return answer